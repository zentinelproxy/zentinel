//! Writes translated Gateway API config as a KDL file for the proxy to read.
//!
//! The gateway controller translates K8s resources into a `Config`, then
//! this module serializes it to a KDL file on a shared volume. The Zentinel
//! proxy runs alongside with `auto-reload: true` and picks up changes
//! automatically via file watching.
//!
//! This is the bridge between the gateway controller (control plane) and
//! the proxy (data plane) in the two-container deployment model.

use std::collections::HashMap;
use std::path::{Path, PathBuf};
use tracing::{info, warn};

use zentinel_config::{
    Config, Filter, FilterConfig, HeaderModifications, MatchCondition, PathModifier, RouteConfig,
    UpstreamConfig,
};

use crate::error::GatewayError;

/// Writes a `Config` to a KDL file that the proxy can read.
pub struct ConfigWriter {
    output_path: PathBuf,
}

impl ConfigWriter {
    pub fn new(output_path: PathBuf) -> Self {
        Self { output_path }
    }

    /// Write the config to disk as KDL.
    ///
    /// Uses an atomic write pattern: write to a temp file, then rename.
    /// This prevents the proxy from reading a partially-written file.
    pub fn write(&self, config: &Config) -> Result<(), std::io::Error> {
        let kdl = self.render_kdl(config);

        // Write atomically via temp file + rename, then re-touch the output
        // file to ensure inotify fires IN_MODIFY (rename only fires
        // IN_MOVED_TO on the directory, which some watchers miss).
        let tmp_path = self.output_path.with_extension("kdl.tmp");
        std::fs::write(&tmp_path, &kdl)?;
        std::fs::rename(&tmp_path, &self.output_path)?;

        // Touch the file to trigger IN_CLOSE_WRITE / IN_MODIFY
        let file = std::fs::OpenOptions::new()
            .append(true)
            .open(&self.output_path)?;
        drop(file);

        info!(
            path = %self.output_path.display(),
            routes = config.routes.len(),
            upstreams = config.upstreams.len(),
            listeners = config.listeners.len(),
            bytes = kdl.len(),
            "Config written to disk"
        );

        Ok(())
    }

    /// Get the output path.
    pub fn output_path(&self) -> &Path {
        &self.output_path
    }

    /// Render a Config as KDL text.
    ///
    /// This produces a minimal but complete KDL config that the proxy can
    /// parse. We generate it programmatically rather than using serde because
    /// the KDL format has specific structure expectations.
    ///
    /// Every value taken from the `Config` is written with [`kdl_string`], so
    /// it is read back as the same single string whatever it contains.
    fn render_kdl(&self, config: &Config) -> String {
        let mut out = String::with_capacity(4096);

        out.push_str("// Auto-generated by zentinel-gateway controller\n");
        out.push_str("// Do not edit manually, changes will be overwritten\n\n");

        out.push_str(&format!(
            "schema-version {}\n\n",
            kdl_string(&config.schema_version)
        ));

        // System block
        out.push_str("system {\n");
        out.push_str(&format!(
            "    worker-threads {}\n",
            config.server.worker_threads
        ));
        if config.server.auto_reload {
            out.push_str("    auto-reload #true\n");
        }
        out.push_str("}\n\n");

        // Listeners
        out.push_str("listeners {\n");
        for listener in &config.listeners {
            out.push_str(&format!("    listener {} {{\n", kdl_string(&listener.id)));
            out.push_str(&format!(
                "        address {}\n",
                kdl_string(&listener.address)
            ));
            let proto = match listener.protocol {
                zentinel_config::ListenerProtocol::Http => "http",
                zentinel_config::ListenerProtocol::Https => "https",
                zentinel_config::ListenerProtocol::Http2 => "h2",
                zentinel_config::ListenerProtocol::Http3 => "h3",
                zentinel_config::ListenerProtocol::H2c => "h2c",
            };
            out.push_str(&format!("        protocol \"{proto}\"\n"));

            if let Some(ref tls) = listener.tls {
                out.push_str("        tls {\n");
                if let Some(ref cert) = tls.cert_file {
                    out.push_str(&format!(
                        "            cert-file {}\n",
                        kdl_string(&cert.to_string_lossy())
                    ));
                }
                if let Some(ref key) = tls.key_file {
                    out.push_str(&format!(
                        "            key-file {}\n",
                        kdl_string(&key.to_string_lossy())
                    ));
                }
                out.push_str("        }\n");
            }

            out.push_str("    }\n");
        }
        out.push_str("}\n\n");

        // Upstreams
        if !config.upstreams.is_empty() {
            out.push_str("upstreams {\n");
            for (id, upstream) in &config.upstreams {
                out.push_str(&format!("    upstream {} {{\n", kdl_string(id)));
                for target in &upstream.targets {
                    out.push_str(&format!("        target {}", kdl_string(&target.address)));
                    if target.weight != 1 {
                        out.push_str(&format!(" weight={}", target.weight));
                    }
                    out.push('\n');
                }

                // Emit load balancing algorithm (omit if default RoundRobin)
                if upstream.load_balancing
                    != zentinel_common::types::LoadBalancingAlgorithm::RoundRobin
                {
                    let algo_str = match upstream.load_balancing {
                        zentinel_common::types::LoadBalancingAlgorithm::Weighted => "weighted",
                        zentinel_common::types::LoadBalancingAlgorithm::LeastConnections => {
                            "least-connections"
                        }
                        zentinel_common::types::LoadBalancingAlgorithm::Random => "random",
                        zentinel_common::types::LoadBalancingAlgorithm::IpHash => "ip-hash",
                        _ => "round-robin",
                    };
                    out.push_str(&format!("        load-balancing \"{algo_str}\"\n"));
                }

                if let Some(ref hc) = upstream.health_check {
                    out.push_str("        health-check {\n");
                    match &hc.check_type {
                        zentinel_common::types::HealthCheckType::Http {
                            path,
                            expected_status,
                            host,
                        } => {
                            out.push_str("            type \"http\"\n");
                            out.push_str(&format!("            path {}\n", kdl_string(path)));
                            out.push_str(&format!(
                                "            expected-status {expected_status}\n"
                            ));
                            if let Some(ref h) = host {
                                out.push_str(&format!("            host {}\n", kdl_string(h)));
                            }
                        }
                        zentinel_common::types::HealthCheckType::Tcp => {
                            out.push_str("            type \"tcp\"\n");
                        }
                        zentinel_common::types::HealthCheckType::Grpc { service } => {
                            out.push_str("            type \"grpc\"\n");
                            if !service.is_empty() {
                                out.push_str(&format!(
                                    "            service {}\n",
                                    kdl_string(service)
                                ));
                            }
                        }
                        _ => {
                            out.push_str("            type \"tcp\"\n");
                        }
                    }
                    out.push_str(&format!("            interval-secs {}\n", hc.interval_secs));
                    out.push_str(&format!("            timeout-secs {}\n", hc.timeout_secs));
                    out.push_str("        }\n");
                }

                out.push_str("    }\n");
            }
            out.push_str("}\n\n");
        }

        // Filters (redirect, rewrite, etc.)
        if !config.filters.is_empty() {
            out.push_str("filters {\n");
            for (id, fc) in &config.filters {
                match &fc.filter {
                    Filter::Redirect(r) => {
                        out.push_str(&format!("    filter {} {{\n", kdl_string(id)));
                        out.push_str("        type \"redirect\"\n");
                        out.push_str(&format!("        status-code {}\n", r.status_code));
                        if let Some(ref h) = r.hostname {
                            out.push_str(&format!("        hostname {}\n", kdl_string(h)));
                        }
                        if let Some(ref s) = r.scheme {
                            out.push_str(&format!("        scheme {}\n", kdl_string(s)));
                        }
                        if let Some(port) = r.port {
                            out.push_str(&format!("        port {port}\n"));
                        }
                        if let Some(ref path) = r.path {
                            render_path_modifier(&mut out, path, 8);
                        }
                        out.push_str("    }\n");
                    }
                    Filter::UrlRewrite(r) => {
                        out.push_str(&format!("    filter {} {{\n", kdl_string(id)));
                        out.push_str("        type \"url-rewrite\"\n");
                        if let Some(ref h) = r.hostname {
                            out.push_str(&format!("        hostname {}\n", kdl_string(h)));
                        }
                        if let Some(ref path) = r.path {
                            render_path_modifier(&mut out, path, 8);
                        }
                        out.push_str("    }\n");
                    }
                    _ => {}
                }
            }
            out.push_str("}\n\n");
        }

        // Routes
        if !config.routes.is_empty() {
            out.push_str("routes {\n");
            for route in &config.routes {
                out.push_str(&format!("    route {} {{\n", kdl_string(&route.id)));

                // Priority (if not default). Emitted as an integer weight to
                // preserve fine-grained numeric priorities set by upstream
                // translators or config sources.
                if route.priority != zentinel_common::types::Priority::NORMAL {
                    out.push_str(&format!("        priority {}\n", route.priority.as_i32()));
                }

                // Match conditions
                out.push_str("        matches {\n");
                for m in &route.matches {
                    match m {
                        zentinel_config::MatchCondition::PathPrefix(p) => {
                            out.push_str(&format!("            path-prefix {}\n", kdl_string(p)));
                        }
                        zentinel_config::MatchCondition::Path(p) => {
                            out.push_str(&format!("            path {}\n", kdl_string(p)));
                        }
                        zentinel_config::MatchCondition::PathRegex(p) => {
                            out.push_str(&format!("            path-regex {}\n", kdl_string(p)));
                        }
                        zentinel_config::MatchCondition::Host(h) => {
                            out.push_str(&format!("            host {}\n", kdl_string(h)));
                        }
                        zentinel_config::MatchCondition::Header { name, value } => {
                            if let Some(v) = value {
                                out.push_str(&format!(
                                    "            header {} {}\n",
                                    kdl_string(name),
                                    kdl_string(v)
                                ));
                            } else {
                                out.push_str(&format!("            header {}\n", kdl_string(name)));
                            }
                        }
                        zentinel_config::MatchCondition::Method(methods) => {
                            for method in methods {
                                out.push_str(&format!(
                                    "            method {}\n",
                                    kdl_string(method)
                                ));
                            }
                        }
                        zentinel_config::MatchCondition::QueryParam { name, value } => {
                            if let Some(v) = value {
                                out.push_str(&format!(
                                    "            query-param {} {}\n",
                                    kdl_string(name),
                                    kdl_string(v)
                                ));
                            }
                        }
                    }
                }
                out.push_str("        }\n");

                if let Some(ref upstream) = route.upstream {
                    out.push_str(&format!("        upstream {}\n", kdl_string(upstream)));
                }

                // Route-level filters (referenced by ID)
                if !route.filters.is_empty() {
                    out.push_str("        filters");
                    for filter_id in &route.filters {
                        out.push_str(&format!(" {}", kdl_string(filter_id)));
                    }
                    out.push('\n');
                }

                // Policies block (header modifications)
                let req_h = &route.policies.request_headers;
                let res_h = &route.policies.response_headers;
                let has_req =
                    !req_h.set.is_empty() || !req_h.add.is_empty() || !req_h.remove.is_empty();
                let has_res =
                    !res_h.set.is_empty() || !res_h.add.is_empty() || !res_h.remove.is_empty();

                if has_req || has_res {
                    out.push_str("        policies {\n");

                    if has_req {
                        out.push_str("            request-headers {\n");
                        render_header_mods_block(&mut out, req_h, 16);
                        out.push_str("            }\n");
                    }

                    if has_res {
                        out.push_str("            response-headers {\n");
                        render_header_mods_block(&mut out, res_h, 16);
                        out.push_str("            }\n");
                    }

                    out.push_str("        }\n");
                }

                out.push_str("    }\n");
            }
            out.push_str("}\n");
        }

        out
    }
}

/// Render header modifications in the nested structure the parser expects.
/// Header names are written as quoted node names, so any name is read back
/// unchanged:
/// ```kdl
/// set {
///     "Header-Name" "value"
/// }
/// add {
///     "Header-Name" "value"
/// }
/// remove "Header-Name" "Other-Header"
/// ```
fn render_header_mods_block(out: &mut String, mods: &HeaderModifications, indent: usize) {
    let pad: String = " ".repeat(indent);
    if !mods.set.is_empty() {
        out.push_str(&format!("{pad}set {{\n"));
        for (k, v) in &mods.set {
            out.push_str(&format!("{pad}    {} {}\n", kdl_string(k), kdl_string(v)));
        }
        out.push_str(&format!("{pad}}}\n"));
    }
    if !mods.add.is_empty() {
        out.push_str(&format!("{pad}add {{\n"));
        for (k, v) in &mods.add {
            out.push_str(&format!("{pad}    {} {}\n", kdl_string(k), kdl_string(v)));
        }
        out.push_str(&format!("{pad}}}\n"));
    }
    if !mods.remove.is_empty() {
        out.push_str(&format!("{pad}remove"));
        for k in &mods.remove {
            out.push_str(&format!(" {}", kdl_string(k)));
        }
        out.push('\n');
    }
}

/// Render a `PathModifier` as KDL at the given indentation level.
fn render_path_modifier(out: &mut String, path: &PathModifier, indent: usize) {
    let pad: String = " ".repeat(indent);
    match path {
        PathModifier::ReplaceFullPath { value } => {
            out.push_str(&format!("{pad}replace-full-path {}\n", kdl_string(value)));
        }
        PathModifier::ReplacePrefixMatch { value } => {
            out.push_str(&format!(
                "{pad}replace-prefix-match {}\n",
                kdl_string(value)
            ));
        }
    }
}

/// Quote `value` as a KDL string.
///
/// Every value that comes from a Kubernetes resource is written through this
/// function. A quote, a backslash or a line break in the value is escaped, so
/// it stays inside the one string instead of ending it or starting another
/// node. The result is always quoted, so a value such as `true` or `123` is
/// read back as a string and not as a keyword or a number. Characters that KDL
/// does not accept as they are (control characters, line and paragraph
/// separators, direction controls and the byte order mark) are written as
/// `\u{..}` escapes.
fn kdl_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if needs_unicode_escape(c) => out.push_str(&format!("\\u{{{:x}}}", u32::from(c))),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Whether `kdl_string` writes `c` as a `\u{..}` escape.
///
/// This covers what KDL does not accept as it is inside a string (line breaks,
/// most control characters, the direction controls and the byte order mark)
/// and what the writer escapes as well so that it stays visible in the file
/// (the other Unicode control characters and the line and paragraph
/// separators).
fn needs_unicode_escape(c: char) -> bool {
    c.is_control()
        || matches!(
            c,
            '\u{2028}'
                | '\u{2029}'
                | '\u{200E}'..='\u{200F}'
                | '\u{202A}'..='\u{202E}'
                | '\u{2066}'..='\u{2069}'
                | '\u{FEFF}'
        )
}

/// A text value that `render_kdl` writes, with the name `check_values` gives
/// it in an error.
struct Field<'a> {
    name: &'static str,
    value: &'a str,
    /// Whether a horizontal tab is accepted in the value.
    allows_tab: bool,
}

impl<'a> Field<'a> {
    fn text(name: &'static str, value: &'a str) -> Self {
        Self {
            name,
            value,
            allows_tab: false,
        }
    }

    /// A header value, where HTTP allows a tab.
    fn header_value(value: &'a str) -> Self {
        Self {
            name: "header value",
            value,
            allows_tab: true,
        }
    }
}

/// Check that the text values of the items translated from one resource can
/// be part of the proxy configuration.
///
/// `kdl_string` makes any value safe to write, but a value with a control
/// character, such as a line break in a path, is not something the proxy can
/// match on. Such a resource is rejected so that it is left out of the
/// configuration, and the reason names the field. A control character is a
/// Unicode control character (U+0000 to U+001F and U+007F to U+009F). A
/// horizontal tab is accepted in a header value, where HTTP allows it.
/// `resource` names the Kubernetes resource the items came from, for the
/// error.
///
/// The fields checked are the ones `render_kdl` writes for routes, upstreams
/// and filters, collected by `route_fields`, `upstream_fields` and
/// `filter_fields`. These are kept in step with `render_kdl` by hand: a field
/// added to `render_kdl` has to be added there and to `CHECKED_FIELDS` in the
/// tests of this module, which checks that every listed field is both written
/// and checked. Listeners are not checked: their ids and certificate paths are
/// made from Kubernetes object names.
///
/// # Errors
///
/// Returns [`GatewayError::InvalidResource`] for the first value that contains
/// a control character.
pub fn check_values(
    resource: &str,
    routes: &[RouteConfig],
    upstreams: &HashMap<String, UpstreamConfig>,
    filters: &HashMap<String, FilterConfig>,
) -> Result<(), GatewayError> {
    let mut fields: Vec<Field<'_>> = Vec::new();
    for route in routes {
        route_fields(route, &mut fields);
    }
    for (id, upstream) in upstreams {
        upstream_fields(id, upstream, &mut fields);
    }
    for (id, filter) in filters {
        filter_fields(id, filter, &mut fields);
    }

    for field in fields {
        let forbidden = field
            .value
            .chars()
            .find(|&c| c.is_control() && !(c == '\t' && field.allows_tab));
        if let Some(c) = forbidden {
            return Err(GatewayError::InvalidResource {
                name: resource.to_string(),
                reason: format!(
                    "{} contains the control character U+{:04X}",
                    field.name,
                    u32::from(c)
                ),
            });
        }
    }
    Ok(())
}

/// Collect the text values `render_kdl` writes for a route.
fn route_fields<'a>(route: &'a RouteConfig, fields: &mut Vec<Field<'a>>) {
    fields.push(Field::text("route id", &route.id));
    if let Some(upstream) = &route.upstream {
        fields.push(Field::text("route upstream", upstream));
    }
    fields.extend(
        route
            .filters
            .iter()
            .map(|id| Field::text("route filter", id)),
    );

    for m in &route.matches {
        match m {
            MatchCondition::PathPrefix(p) => fields.push(Field::text("path-prefix", p)),
            MatchCondition::Path(p) => fields.push(Field::text("path", p)),
            MatchCondition::PathRegex(p) => fields.push(Field::text("path-regex", p)),
            MatchCondition::Host(h) => fields.push(Field::text("host", h)),
            MatchCondition::Header { name, value } => {
                fields.push(Field::text("header name", name));
                if let Some(v) = value {
                    fields.push(Field::header_value(v));
                }
            }
            MatchCondition::Method(methods) => {
                fields.extend(methods.iter().map(|m| Field::text("method", m)));
            }
            MatchCondition::QueryParam { name, value } => {
                fields.push(Field::text("query-param name", name));
                if let Some(v) = value {
                    fields.push(Field::text("query-param value", v));
                }
            }
        }
    }

    for mods in [
        &route.policies.request_headers,
        &route.policies.response_headers,
    ] {
        for (name, value) in mods.set.iter().chain(&mods.add) {
            fields.push(Field::text("header name", name));
            fields.push(Field::header_value(value));
        }
        fields.extend(
            mods.remove
                .iter()
                .map(|name| Field::text("header name", name)),
        );
    }
}

/// Collect the text values `render_kdl` writes for an upstream.
fn upstream_fields<'a>(id: &'a str, upstream: &'a UpstreamConfig, fields: &mut Vec<Field<'a>>) {
    fields.push(Field::text("upstream id", id));
    fields.extend(
        upstream
            .targets
            .iter()
            .map(|target| Field::text("upstream target", &target.address)),
    );
    match upstream.health_check.as_ref().map(|hc| &hc.check_type) {
        Some(zentinel_common::types::HealthCheckType::Http { path, host, .. }) => {
            fields.push(Field::text("health-check path", path));
            if let Some(host) = host {
                fields.push(Field::text("health-check host", host));
            }
        }
        Some(zentinel_common::types::HealthCheckType::Grpc { service }) => {
            fields.push(Field::text("health-check service", service));
        }
        _ => {}
    }
}

/// Collect the text values `render_kdl` writes for a filter.
fn filter_fields<'a>(id: &'a str, filter: &'a FilterConfig, fields: &mut Vec<Field<'a>>) {
    fields.push(Field::text("filter id", id));
    let (hostname, scheme, path) = match &filter.filter {
        Filter::Redirect(r) => (&r.hostname, r.scheme.as_ref(), &r.path),
        Filter::UrlRewrite(r) => (&r.hostname, None, &r.path),
        _ => return,
    };
    if let Some(hostname) = hostname {
        fields.push(Field::text("filter hostname", hostname));
    }
    if let Some(scheme) = scheme {
        fields.push(Field::text("filter scheme", scheme));
    }
    match path {
        Some(PathModifier::ReplaceFullPath { value })
        | Some(PathModifier::ReplacePrefixMatch { value }) => {
            fields.push(Field::text("filter path", value));
        }
        None => {}
    }
}

/// Write a minimal bootstrap config for the proxy to start with before
/// the controller has reconciled any Gateway API resources.
///
/// The HTTPS listener starts with a self-signed certificate so Pingora
/// can bind the TLS listener. The real certificate from the Gateway's
/// Secret will replace it when the controller reconciles.
pub fn write_bootstrap_config(path: &Path) -> Result<(), std::io::Error> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }

    // Generate a self-signed bootstrap certificate for the HTTPS listener
    let cert_dir = std::path::Path::new("/tmp/zentinel-gateway-certs");
    std::fs::create_dir_all(cert_dir)?;
    let cert_path = cert_dir.join("bootstrap.crt");
    let key_path = cert_dir.join("bootstrap.key");

    generate_self_signed_cert(&cert_path, &key_path)?;

    let kdl = format!(
        r#"// Bootstrap config for Zentinel Gateway API controller
// Will be overwritten once the controller reconciles Gateway resources

schema-version "1.0"

system {{
    worker-threads 0
    auto-reload #true
}}

listeners {{
    listener "http" {{
        address "0.0.0.0:8080"
        protocol "http"
    }}
    listener "https" {{
        address "0.0.0.0:8443"
        protocol "https"
        tls {{
            cert-file "{cert}"
            key-file "{key}"
        }}
    }}
}}
"#,
        cert = cert_path.display(),
        key = key_path.display()
    );

    std::fs::write(path, kdl)?;
    info!(path = %path.display(), "Bootstrap config written with self-signed TLS cert");
    Ok(())
}

/// Generate a self-signed certificate for bootstrap TLS.
fn generate_self_signed_cert(
    cert_path: &std::path::Path,
    key_path: &std::path::Path,
) -> Result<(), std::io::Error> {
    use std::process::Command;

    // Use openssl to generate a self-signed cert (available in most containers)
    let status = Command::new("openssl")
        .args([
            "req",
            "-x509",
            "-newkey",
            "ec",
            "-pkeyopt",
            "ec_paramgen_curve:prime256v1",
            "-keyout",
        ])
        .arg(key_path)
        .args(["-out"])
        .arg(cert_path)
        .args([
            "-days",
            "1",
            "-nodes",
            "-subj",
            "/CN=zentinel-bootstrap",
            "-batch",
        ])
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status();

    match status {
        Ok(s) if s.success() => {
            info!(
                cert = %cert_path.display(),
                key = %key_path.display(),
                "Generated self-signed bootstrap TLS certificate"
            );
            Ok(())
        }
        _ => {
            // Fallback: write minimal PEM files that Pingora can parse
            // (they won't validate but allow the listener to start)
            warn!("openssl not available, writing placeholder TLS cert");
            // Generate using rcgen if available, or write a static self-signed cert
            write_fallback_self_signed_cert(cert_path, key_path)
        }
    }
}

/// Write a static self-signed PEM cert as fallback when openssl is unavailable.
fn write_fallback_self_signed_cert(
    cert_path: &std::path::Path,
    key_path: &std::path::Path,
) -> Result<(), std::io::Error> {
    // Use rcgen to generate a self-signed certificate
    let subject_alt_names = vec!["localhost".to_string()];
    let cert =
        rcgen::generate_simple_self_signed(subject_alt_names).map_err(std::io::Error::other)?;

    std::fs::write(cert_path, cert.cert.pem())?;
    std::fs::write(key_path, cert.signing_key.serialize_pem())?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(key_path, std::fs::Permissions::from_mode(0o600));
    }

    Ok(())
}

